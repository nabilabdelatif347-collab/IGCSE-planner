const CACHE = `igcse-planner-${VERSION}`;
const FONT_CACHE = 'igcse-planner-fonts';
// The app shell is cached as the scope root ("/"), not "/index.html", which some hosts redirect.
const INDEX = self.registration.scope;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((path) => new Request(new URL(path, self.registration.scope), { cache: 'reload' })))),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('igcse-planner-') && k !== CACHE && k !== FONT_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

// Daily study reminder: tapping it opens (or focuses) the planner on the study plan.
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windows) => {
      const open = windows.find((w) => w.url.startsWith(self.registration.scope));
      return open ? open.focus() : self.clients.openWindow(`${self.registration.scope}#plan`);
    }),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);

  if (url.origin === self.location.origin) {
    if (request.mode === 'navigate') {
      // Single-page app: every page load is index.html (views live in the #hash).
      event.respondWith(caches.open(CACHE).then((c) => c.match(INDEX)).then((hit) => hit ?? fetch(request)));
      return;
    }
    event.respondWith(
      caches
        .open(CACHE)
        .then((c) => c.match(request, { ignoreSearch: true }))
        .then((hit) => hit ?? fetch(request)),
    );
    return;
  }

  // Google Fonts: the stylesheet is refreshed in the background, font files never change.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(
      caches.open(FONT_CACHE).then(async (cache) => {
        const hit = await cache.match(request);
        const refresh = fetch(request)
          .then((res) => {
            if (res.ok || res.type === 'opaque') cache.put(request, res.clone());
            return res;
          })
          .catch(() => hit);
        if (hit && url.hostname === 'fonts.googleapis.com') event.waitUntil(refresh);
        return hit ?? refresh;
      }),
    );
  }
});
